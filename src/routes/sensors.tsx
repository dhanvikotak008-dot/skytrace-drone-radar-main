import { createFileRoute } from "@tanstack/react-router";
import { Camera, Cpu, Radio, RadioReceiver, Wifi, Info } from "lucide-react";
import type { ReactNode } from "react";
import { PageHeader, Panel, Stat } from "@/components/hud";
import { SENSOR_NAME, useSim, type SensorKey } from "@/sim/store";
import { RADAR, beatHz, range2, range3 } from "@/sim/model";

export const Route = createFileRoute("/sensors")({
  head: () => ({
    meta: [
      { title: "Sensor Monitoring — SkyWatch-MD" },
      { name: "description", content: "Status, signal quality and readings of simulated FMCW radar, receiver, camera, RF and IoT sensors." },
      { property: "og:title", content: "Sensor Monitoring — SkyWatch-MD" },
      { property: "og:description", content: "Simulated multi-sensor health dashboard." },
    ],
  }),
  component: Sensors,
});

function Sensors() {
  const f = useSim((s) => s.failures);
  const sensor = useSim((s) => s.sensor);
  const noise = useSim((s) => s.noise);
  const targets = useSim((s) => s.targets);
  const det = targets.filter((t) => t.detected);
  const avgSnr = det.length ? det.reduce((a, t) => a + t.snrDb, 0) / det.length : 0;
  const inCam = targets.filter((t) => range2(t.pos) < 2000);
  const rfHits = targets.filter((t) => t.truth === "drone" && range2(t.pos) < 3000);
  const nearest = det.length ? Math.min(...det.map((t) => range3(t.pos))) : 0;
  const q = (base: number) => Math.max(0, Math.round(base * (1 - noise * 0.6)));

  return (
    <>
      <PageHeader code="MODULE 06 / SNS" title="Sensor Monitoring" desc="Health and readings of the modelled sensor suite. Readings are generated by the simulator.">
        <span className="inline-flex items-center gap-1 rounded-sm border border-danger/50 px-2 py-0.5 font-mono text-[10px] text-danger"><Info className="h-3 w-3" />NO PHYSICAL HARDWARE CONNECTED</span>
      </PageHeader>
      <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
        <SensorCard k="radar" icon={<Radio className="h-4 w-4" />} failed={f.radar} quality={q(94)} link="Local bus (sim)">
          <Stat label="Carrier" value={RADAR.fc / 1e9} unit="GHz" />
          <Stat label="Chirp BW" value={RADAR.chirpBw / 1e6} unit="MHz" sub={`range res ${(RADAR.c / (2 * RADAR.chirpBw)).toFixed(1)} m`} />
          <Stat label="Tx power" value={f.radar ? 0 : RADAR.Pt} unit="W" />
          <Stat label="Module temp" value={sensor.radarTemp.toFixed(1)} unit="°C" tone={sensor.radarTemp > 55 ? "warn" : "foreground"} />
          <Stat label="Beat freq @ nearest" value={nearest ? (beatHz(nearest) / 1e6).toFixed(2) : "—"} unit="MHz" sub="f_b = 2RS/c" />
          <Stat label="Sweep" value={f.radar ? "HALT" : "1 ms"} />
        </SensorCard>
        <SensorCard k="receiver" icon={<RadioReceiver className="h-4 w-4" />} failed={false} degraded={f.receiver} quality={f.receiver ? q(45) : q(90)} link="Local bus (sim)">
          <Stat label="Noise floor" value={(-114 + (f.receiver ? 10 : 0) + noise * 8).toFixed(1)} unit="dBm" />
          <Stat label="Noise figure" value={RADAR.noiseFigDb + (f.receiver ? 10 : 0)} unit="dB" tone={f.receiver ? "warn" : "foreground"} />
          <Stat label="Mean target SNR" value={det.length ? avgSnr.toFixed(1) : "—"} unit="dB" tone="radar" />
          <Stat label="Detections" value={det.length} />
        </SensorCard>
        <SensorCard k="camera" icon={<Camera className="h-4 w-4" />} failed={f.camera} quality={q(82)} link="Ethernet (sim)">
          <Stat label="Frame rate" value={sensor.fps} unit="fps" />
          <Stat label="Objects in FOV (<2 km)" value={f.camera ? "—" : inCam.length} />
          <Stat label="Mode" value="EO / day" />
          <Stat label="Fusion" value={f.camera ? "OFF" : "ACTIVE"} tone={f.camera ? "danger" : "radar"} />
        </SensorCard>
        <SensorCard k="rf" icon={<Wifi className="h-4 w-4" />} failed={f.rf} quality={q(76)} link="USB (sim)" optional>
          <Stat label="Bands" value="2.4 / 5.8" unit="GHz" />
          <Stat label="Control-link hits (<3 km)" value={f.rf ? "—" : rfHits.length} tone={rfHits.length ? "warn" : "foreground"} />
          <Stat label="Strongest RSSI" value={f.rf || !rfHits.length ? "—" : (-40 - Math.min(...rfHits.map((t) => range2(t.pos))) / 60).toFixed(0)} unit="dBm" />
          <Stat label="Mode" value="Passive listen" />
        </SensorCard>
        <SensorCard k="iot" icon={<Cpu className="h-4 w-4" />} failed={f.iot} quality={f.iot ? 0 : q(Math.round(100 - sensor.packetLoss * 8))} link="MQTT (sim)">
          <Stat label="Latency" value={f.iot ? "—" : sensor.latencyMs.toFixed(0)} unit="ms" />
          <Stat label="Packet loss" value={sensor.packetLoss.toFixed(1)} unit="%" tone={sensor.packetLoss > 2 ? "warn" : "foreground"} />
          <Stat label="Node battery" value={sensor.battery.toFixed(1)} unit="%" />
          <Stat label="Heartbeat" value={f.iot ? "LOST" : "OK"} tone={f.iot ? "danger" : "radar"} />
        </SensorCard>
        <Panel title="Data provenance">
          <ul className="space-y-2 text-sm text-muted-foreground">
            <li><span className="text-amber">■ Simulated</span> — every value on this page is produced by the in-browser simulation model.</li>
            <li><span className="text-radar">■ Measured</span> — none. No radar, camera, RF receiver or IoT node is connected to this application.</li>
            <li>Inject faults from the <b className="text-cyan">Control Center</b> to see how degraded sensors affect detection and classification.</li>
          </ul>
        </Panel>
      </div>
    </>
  );
}

function SensorCard({ k, icon, failed, degraded, quality, link, optional, children }: { k: SensorKey; icon: ReactNode; failed: boolean; degraded?: boolean; quality: number; link: string; optional?: boolean; children: ReactNode }) {
  const status = failed ? "OFFLINE" : degraded ? "DEGRADED" : "ONLINE";
  const tone = failed ? "danger" : degraded ? "warn" : "radar";
  return (
    <Panel title={SENSOR_NAME[k] + (optional ? " (optional)" : "")} icon={icon} right={<span className={`rounded-sm border border-${tone} px-1.5 py-0.5 font-mono text-[10px] font-bold text-${tone}`}>{status}</span>}>
      <div className="mb-3 flex items-center gap-3 font-mono text-[11px] text-muted-foreground">
        <span>Signal quality</span>
        <div className="h-1.5 flex-1 overflow-hidden rounded-full bg-muted"><div className={`h-full bg-${tone} transition-all`} style={{ width: `${failed ? 0 : quality}%` }} /></div>
        <span className={`text-${tone}`}>{failed ? 0 : quality}%</span>
      </div>
      <div className="mb-3 font-mono text-[10px] text-muted-foreground">Connectivity: {failed ? "disconnected" : link} · source: SIMULATOR</div>
      <div className="grid grid-cols-2 gap-2">{children}</div>
    </Panel>
  );
}
